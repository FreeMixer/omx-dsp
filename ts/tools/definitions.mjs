/**
 * ts/src/definitions.ts from omx-dsp's own data/ (the kernel constants the twins read; the owner rule of
 * 2026-10-21 puts DSP kernel constants in omx-dsp, not omx-contract). `--check` exits 1 when the committed
 * file is not what the data renders. Only the constants a twin reads are rendered (NAMES below).
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const TS = join(dirname(fileURLToPath(import.meta.url)), '..');
const DATA = join(TS, '..', 'data', 'kernels');
const OUT = join(TS, 'src', 'definitions.ts');
/** data file -> the constants of it a twin reads */
const NAMES = { 'rta.json': ['RTA_TARGET_BIN_HZ', 'RTA_FFT_SIZE_MAX'] };

export const render = () => {
  const lines = [
    '// SPDX-License-Identifier: GPL-3.0-or-later',
    '// Copyright (C) 2026 Pau Aliagas <linuxnow@gmail.com>',
    '// GENERATED by ts/tools/definitions.mjs from omx-dsp data/kernels/ - do not edit.',
  ];
  for (const [file, names] of Object.entries(NAMES)) {
    const constants = JSON.parse(readFileSync(join(DATA, file), 'utf8')).constants;
    for (const name of names) {
      const c = constants[name];
      if (!c || c.kind !== 'scalar' || typeof c.value !== 'number') throw new Error(`data/kernels/${file}: ${name} is no scalar`);
      lines.push('', `/** ${c.doc.replace(/\*\//g, '*\\/')}${c.unit ? ` (${c.unit})` : ''} @see data/kernels/${file} */`, `export const ${name} = ${c.value};`);
    }
  }
  return lines.join('\n') + '\n';
};

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const want = render();
  if (process.argv.includes('--check')) {
    let have = '';
    try { have = readFileSync(OUT, 'utf8'); } catch {}
    if (have !== want) { console.error(`${OUT} is not what data/kernels renders: run node ts/tools/definitions.mjs`); process.exit(1); }
  } else writeFileSync(OUT, want);
}
