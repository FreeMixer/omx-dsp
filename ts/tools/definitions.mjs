/**
 * ts/src/definitions.ts from omx-dsp's own data/ (the kernel constants the twins read; the owner rule of
 * 2026-10-21 puts DSP kernel constants in omx-dsp, not omx-contract). `--check` exits 1 when the committed
 * file is not what the data renders. Only what a twin reads is rendered: the constants in CONSTANTS and the
 * control travels in TRAVELS.
 *
 * A `{ "ref": NAME }` inside a sheet resolves to NAME in omx-dsp's data when it is one of its scalars, else to
 * the committed include/omxdsp/omxdsp_definitions.h, which is omx-contract's render of the same declarations
 * (make definitions-check holds it equal), so no value is written twice. The items of data/primitives/ in
 * PRIMITIVES are rendered the same way, a set as its ids in order (the value of each is its position).
 */
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const TS = join(dirname(fileURLToPath(import.meta.url)), '..');
const DATA = join(TS, '..', 'data', 'kernels');
const PRIM = join(TS, '..', 'data', 'primitives');
const HEADER = join(TS, '..', 'include', 'omxdsp', 'omxdsp_definitions.h');
const OUT = join(TS, 'src', 'definitions.ts');
/** data file -> the constants of it a twin reads */
const CONSTANTS = {
  'rta.json': ['RTA_TARGET_BIN_HZ', 'RTA_FFT_SIZE_MAX'],
  'eq.json': ['LOWPASS_HANDOVER', 'EQ_BAND_DEFAULTS'],
  'fbs.json': ['FBS_MAX_CUT_DB', 'FBS_RECLAMP_DEEPEN_DB', 'FBS_RECLAMP_BACKOFF_CAP', 'FBS_LIFT_RAMP_MS', 'FBS_LIFT_RAMP_STEPS', 'FBS_RELEASE_RATIO',
    'FBS_RELEASE_DONE_DB', 'FBS_RELEASE_DWELL_MS', 'FBS_RING_HZ_MIN', 'FBS_RING_HZ_MAX', 'FBS_SAME_RING_HZ', 'FBS_SAME_RING_SHARE',
    'FBS_DEFAULT_HOLD_SECONDS', 'FBS_DEFAULT_MAX_AUTO_BANDS', 'FBS_DEFAULT_MERGE_CENTS', 'FBS_DEFAULT_COOLDOWN_SECONDS', 'FBS_DEFAULT_NOTCH_Q',
    'FBS_RING_MEMORY_SLOTS'],
};
/** data file -> control name -> the exported name of its { min, max } travel */
const TRAVELS = {
  'eq.json': { q: 'EQ_Q_RANGE', notchQ: 'EQ_NOTCH_Q_RANGE', gain: 'EQ_GAIN_RANGE', freq: 'EQ_FREQ_RANGE' },
  'fbs.json': { bands: 'FBS_BANDS_RANGE', hold: 'FBS_HOLD_RANGE', merge: 'FBS_MERGE_RANGE', cooldown: 'FBS_COOLDOWN_RANGE' },
  'comp.json': { ratio: 'COMP_RATIO_RANGE', kneeDb: 'COMP_KNEE_DB_RANGE' },
  'gate.json': { ratio: 'GATE_RATIO_RANGE', rangeDb: 'GATE_RANGE_DB_RANGE' },
};
/** data/primitives file -> the items of it a twin reads */
const PRIMITIVES = {
  'curve.json': ['CURVE_DISPLAYS', 'CURVE_FAMILIES', 'CURVE_ROLES', 'CURVE_UNITS', 'CURVE_SHAPES', 'CURVE_ORIGINS', 'CURVE_CODES', 'CURVE_POINTS_MAX', 'CURVE_EXTENTS'],
  'lin-to-db-floor.json': ['LIN_TO_DB_FLOOR'],
  'meter.json': ['METER_VIEW', 'METER_KINDS', 'METER_MEASUREMENTS', 'METER_UNITS', 'METER_DECIMATION'],
};

const read = (file) => JSON.parse(readFileSync(join(DATA, file), 'utf8'));

const scalars = () => {
  const out = new Map();
  for (const f of readdirSync(DATA).filter((n) => n.endsWith('.json')))
    for (const [k, c] of Object.entries(read(f).constants ?? {})) if (c.kind === 'scalar' && typeof c.value === 'number') out.set(k, c.value);
  return out;
};

const fromHeader = (name) => {
  const h = readFileSync(HEADER, 'utf8');
  for (const macro of [`OMX_${name}_DOUBLE`, `OMX_${name}`]) {
    const m = h.match(new RegExp(`^#define ${macro} (-?[0-9.eE+-]+?)f?$`, 'm'));
    if (m) return Number(m[1]);
  }
  throw new Error(`ref ${name}: neither omx-dsp data nor ${HEADER} defines it`);
};

const resolve = (v, own) => {
  if (typeof v === 'number') return v;
  if (v && typeof v === 'object' && typeof v.ref === 'string') return own.has(v.ref) ? own.get(v.ref) : fromHeader(v.ref);
  throw new Error(`a sheet value is neither a number nor a ref: ${JSON.stringify(v)}`);
};

const doc = (text, file, unit, dir = 'kernels') => `/** ${text.replace(/\*\//g, '*\\/')}${unit ? ` (${unit})` : ''} @see data/${dir}/${file} */`;

export const render = () => {
  const own = scalars();
  const lines = [
    '// SPDX-License-Identifier: GPL-3.0-or-later',
    '// Copyright (C) 2026 Pau Aliagas <linuxnow@gmail.com>',
    '// GENERATED by ts/tools/definitions.mjs from omx-dsp data/ - do not edit.',
  ];
  for (const [file, names] of Object.entries(CONSTANTS)) {
    const constants = read(file).constants;
    for (const name of names) {
      const c = constants[name];
      if (c?.kind === 'scalar' && typeof c.value === 'number') {
        lines.push('', doc(c.doc, file, c.unit), `export const ${name} = ${c.value};`);
      } else if (c?.kind === 'sheet' && c.value && typeof c.value === 'object') {
        const body = Object.entries(c.value).map(([k, v]) => `  ${k}: ${resolve(v, own)},`);
        lines.push('', doc(c.doc, file), `export const ${name} = {`, ...body, '} as const;');
      } else throw new Error(`data/kernels/${file}: ${name} is no scalar or flat sheet`);
    }
  }
  for (const [file, names] of Object.entries(PRIMITIVES)) {
    const items = JSON.parse(readFileSync(join(PRIM, file), 'utf8'));
    for (const name of names) {
      const c = items[name];
      if (c?.kind === 'scalar' && typeof c.value === 'number') {
        lines.push('', doc(c.doc, file, c.unit, 'primitives'), `export const ${name} = ${c.value};`);
      } else if (c?.kind === 'sheet' && c.value && typeof c.value === 'object') {
        const body = Object.entries(c.value).map(([k, v]) => `  ${k}: ${resolve(v, own)},`);
        lines.push('', doc(c.doc, file, undefined, 'primitives'), `export const ${name} = {`, ...body, '} as const;');
      } else if (c?.kind === 'set' && Array.isArray(c.ids) && c.ids.every((i) => typeof i === 'string')) {
        lines.push('', doc(c.doc, file, undefined, 'primitives'), `export const ${name} = [${c.ids.map((i) => `'${i}'`).join(', ')}] as const;`);
        if (Array.isArray(c.labels))
          lines.push('', `/** The labels of ${name}, in its order. @see data/primitives/${file} */`, `export const ${name}_LABELS = [${c.labels.map((i) => `'${i}'`).join(', ')}] as const;`);
      } else throw new Error(`data/primitives/${file}: ${name} is no scalar, flat sheet or set of named ids`);
    }
  }
  for (const [file, controls] of Object.entries(TRAVELS)) {
    const all = read(file).controls;
    for (const [control, name] of Object.entries(controls)) {
      const c = all.find((x) => x.name === control);
      if (!c || c.kind !== 'travel' || c.travel?.min === undefined || c.travel?.max === undefined)
        throw new Error(`data/kernels/${file}: control ${control} has no travel`);
      lines.push('', doc(c.doc ?? `The travel of ${control}, from its table ${c.table}.`, file), `export const ${name} = { min: ${resolve(c.travel.min, own)}, max: ${resolve(c.travel.max, own)} } as const;`);
    }
  }
  return lines.join('\n') + '\n';
};

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const want = render();
  if (process.argv.includes('--check')) {
    let have = '';
    try { have = readFileSync(OUT, 'utf8'); } catch {}
    if (have !== want) { console.error(`${OUT} is not what data/kernels renders: run node ts/tools/definitions.mjs`); process.exit(1); }
  } else writeFileSync(OUT, want);
}
