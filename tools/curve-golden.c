/*
 * curve-golden — writes test/kernels/fixtures/curve_golden.h: omx_curve_points_marked() over each request of
 * test/kernels/fixtures/curve_requests.h, every point "%.17g", so no value is rounded on the way. Run by
 * `make curve-golden`; the suite's curve arm reads the file back. A change of law re-runs it in the commit that
 * makes the change, and the diff is the review.
 */
#include <stdio.h>

#include "../test/kernels/fixtures/curve_requests.h"

int main(void) {
  static double x[OMX_CURVE_POINTS_MAX], y[OMX_CURVE_POINTS_MAX], yu[OMX_CURVE_POINTS_MAX];
  struct omx_curve_mark marks[8];
  printf("// SPDX-License-Identifier: GPL-3.0-or-later\n// Copyright (C) 2026 Pau Aliagas <linuxnow@gmail.com>\n");
  printf("/* GENERATED by tools/curve-golden.c (make curve-golden) from fixtures/curve_requests.h - do not edit. */\n");
  printf("#ifndef OMXDSP_TEST_CURVE_GOLDEN_H\n#define OMXDSP_TEST_CURVE_GOLDEN_H\n\n#include <omxdsp/omx_curve.h>\n\n");
  printf("static const struct { uint32_t n; double x[%u]; double y[%u]; double y_user[%u]; uint32_t nmarks; "
         "struct omx_curve_mark marks[8]; } CURVE_GOLDEN[%u] = {\n",
         OMX_CURVE_POINTS_MAX, OMX_CURVE_POINTS_MAX, OMX_CURVE_POINTS_MAX, CURVE_GOLDEN_COUNT);
  for (uint32_t k = 0; k < CURVE_GOLDEN_COUNT; k++) {
    int code = -1;
    struct omx_curve_extra ex = {yu, marks, 8u, 0u};
    const uint32_t n = omx_curve_points_marked(CURVE_GOLDEN_REQUESTS[k].rq, x, y, OMX_CURVE_POINTS_MAX, &ex, &code);
    if (code != OMX_CURVE_OK || n == 0) {
      fprintf(stderr, "curve-golden: %s answered code %d\n", CURVE_GOLDEN_REQUESTS[k].name, code);
      return 1;
    }
    printf("    /* %s */ {%u,\n     {", CURVE_GOLDEN_REQUESTS[k].name, n);
    for (uint32_t i = 0; i < n; i++) printf("%s%.17g", i ? ", " : "", x[i]);
    printf("},\n     {");
    for (uint32_t i = 0; i < n; i++) printf("%s%.17g", i ? ", " : "", y[i]);
    printf("},\n     {");
    for (uint32_t i = 0; i < n; i++) printf("%s%.17g", i ? ", " : "", yu[i]);
    printf("},\n     %u, {", ex.nmarks);
    for (uint32_t i = 0; i < ex.nmarks; i++)
      printf("%s{%.17g, %.17g, %.17g, %d}", i ? ", " : "", marks[i].freq_hz, marks[i].depth_db, marks[i].q, (int)marks[i].origin);
    printf("}},\n");
  }
  printf("};\n\n#endif /* OMXDSP_TEST_CURVE_GOLDEN_H */\n");
  return 0;
}
