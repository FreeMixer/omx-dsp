/*
 * meter-view-golden — writes vectors/meter-view.json: the meter view law (mix/omx_meter_view.h) over the scenarios of
 * test/kernels/fixtures/meter_view_scenarios.h, every number "%.17g", so no value is rounded on the way. Run by
 * `make meter-view-golden`; the suite's mix_meter_view arm, the TypeScript twin's test and any other copy of the law
 * read the file back. One case per line. A change of law re-runs it in the commit that makes the change, and the diff
 * is the review.
 */
#include <stdio.h>

#include "../test/kernels/fixtures/meter_view_scenarios.h"

static void arr(const char *key, const double *x, uint32_t n) {
  printf(", \"%s\": [", key);
  for (uint32_t i = 0; i < n; i++) printf("%s%.17g", i ? ", " : "", x[i]);
  printf("]");
}

int main(void) {
  static struct mv_reads r;
  static double a[MV_MAX_TICKS], b[MV_MAX_TICKS], c[MV_MAX_TICKS], d[MV_MAX_TICKS];
  printf("{\n");
  printf("  \"doc\": \"GENERATED by tools/meter-view-golden.c (make meter-view-golden) - do not edit. The meter view law of "
         "omx_meter_view.h at the oracle rates and quanta 32 to 1024: held, a burst read at hostReadHz, its fill and the "
         "marker stepped by the time since the last read; gr, the deepest reduction kept between reads and the reading "
         "recovered by omx_meter_gr_step over that time; fall, the marker after full scale at each draw rate; ladder, "
         "clip, fillDb, fillLinear and decimate, the rest of the law. One case per line.\",\n");
  printf("  \"law\": {\"floorDb\": %.17g, \"fallDbPerSecond\": %.17g, \"stepHysteresis\": %.17g, \"hostReadHz\": %.17g, "
         "\"streamHz\": %.17g, \"grHoldMs\": %.17g},\n",
         (double)OMX_METER_VIEW_FLOOR_DB, (double)OMX_METER_VIEW_FALL_DB_PER_SECOND,
         OMX_METER_VIEW_STEP_HYSTERESIS_DOUBLE, (double)OMX_METER_VIEW_HOST_READ_HZ, (double)OMX_METER_VIEW_STREAM_HZ,
         (double)OMX_METER_GR_HOLD_MS);
  printf("  \"cases\": [\n");
  int first = 1;
#define OPEN(...) (printf("%s    {", first ? "" : ",\n"), first = 0, printf(__VA_ARGS__))
  for (uint32_t ri = 0; ri < MV_RATES_COUNT; ri++)
    for (uint32_t qi = 0; qi < MV_QUANTA_COUNT; qi++) {
      mv_held(MV_RATES[ri], MV_QUANTA[qi], &r);
      OPEN("\"set\": \"held\", \"rate\": %.17g, \"quantum\": %u", (double)MV_RATES[ri], MV_QUANTA[qi]);
      arr("peak", r.in, r.n), arr("dt", r.dt, r.n), arr("fill", r.out, r.n), arr("marker", r.marker, r.n);
      printf("}");
    }
  for (uint32_t ri = 0; ri < MV_RATES_COUNT; ri++)
    for (uint32_t qi = 0; qi < MV_QUANTA_COUNT; qi++) {
      mv_gr(MV_RATES[ri], MV_QUANTA[qi], &r);
      OPEN("\"set\": \"gr\", \"rate\": %.17g, \"quantum\": %u, \"pole\": %.17g", (double)MV_RATES[ri], MV_QUANTA[qi],
           (double)mv_pole(MV_RATES[ri]));
      arr("deepest", r.in, r.n), arr("dt", r.dt, r.n), arr("reading", r.out, r.n);
      printf("}");
    }
  for (uint32_t li = 0; li < 2u; li++)
    for (uint32_t hi = 0; hi < MV_DRAW_COUNT; hi++) {
      const double live = li ? omx_meter_view_fill_db(-30.0, OMX_METER_VIEW_FLOOR_DB) : 0.0;
      const uint32_t n = mv_fall(MV_DRAW_HZ[hi], live, a);
      OPEN("\"set\": \"fall\", \"drawHz\": %.17g, \"live\": %.17g", MV_DRAW_HZ[hi], live);
      arr("marker", a, n);
      printf("}");
    }
  mv_ladder_fills(a);
  int32_t prev = -1;
  for (uint32_t i = 0; i < MV_LADDER_COUNT; i++)
    b[i] = prev = omx_meter_view_ladder(prev, a[i], MV_LADDER_STEPS, OMX_METER_VIEW_STEP_HYSTERESIS_DOUBLE);
  OPEN("\"set\": \"ladder\", \"steps\": %u, \"hysteresis\": %.17g", MV_LADDER_STEPS, OMX_METER_VIEW_STEP_HYSTERESIS_DOUBLE);
  arr("fill", a, MV_LADDER_COUNT), arr("count", b, MV_LADDER_COUNT);
  printf("}");
  struct omx_meter_view v = {0};
  for (uint32_t i = 0; i < MV_CLIP_COUNT; i++) {
    a[i] = MV_CLIP_IN[i][0], b[i] = MV_CLIP_IN[i][1];
    c[i] = mv_clip_tick(&v, MV_CLIP_IN[i][0], MV_CLIP_IN[i][1]);
  }
  OPEN("\"set\": \"clip\"");
  arr("clip", a, MV_CLIP_COUNT), arr("clear", b, MV_CLIP_COUNT), arr("lit", c, MV_CLIP_COUNT);
  printf("}");
  for (uint32_t i = 0; i < MV_FILL_DB_COUNT; i++) a[i] = omx_meter_view_fill_db(MV_FILL_DB[i], OMX_METER_VIEW_FLOOR_DB);
  OPEN("\"set\": \"fillDb\"");
  arr("db", MV_FILL_DB, MV_FILL_DB_COUNT), arr("fill", a, MV_FILL_DB_COUNT);
  printf("}");
  for (uint32_t i = 0; i < MV_FILL_LIN_COUNT; i++) a[i] = omx_meter_view_fill(MV_FILL_LIN[i], OMX_METER_VIEW_FLOOR_DB);
  OPEN("\"set\": \"fillLinear\"");
  arr("level", MV_FILL_LIN, MV_FILL_LIN_COUNT), arr("fill", a, MV_FILL_LIN_COUNT);
  printf("}");
  static const double KEPT[] = {0.25, 0.25, 0.5, -6.0, -6.0, -3.0}, VAL[] = {0.5, 0.125, 0.5, -9.0, -3.0, -3.0};
  for (uint32_t i = 0; i < 6u; i++) {
    a[i] = i < 3u ? OMX_METER_KINDS_LEVEL : OMX_METER_KINDS_GAIN_REDUCTION;
    d[i] = omx_meter_view_decimate((enum omx_meter_kinds)(int)a[i], KEPT[i], VAL[i]);
  }
  OPEN("\"set\": \"decimate\"");
  arr("kind", a, 6u), arr("kept", KEPT, 6u), arr("value", VAL, 6u), arr("out", d, 6u);
  printf("}\n  ]\n}\n");
  return 0;
}
