# sabotage.sh <dir> <libomxdsp-contracts.a> — the mix module's oracles and digests are not blind
# (FreeMixer/omx-dsp#98). For each kernel, one line of a SABOTAGED COPY of its header, placed ahead
# of the real include directory, moves its arithmetic; the mix arms of the suite (test/kernels/
# mix_*.c, built alone) must then fail that kernel's arm, and test/mix/golden.test.c must move that
# kernel's digests. First the control: the same mix arms against the real headers fail nothing.
# The tree is never edited; a sed that matches nothing is a failure, not a skip.
# Usage: CC=… CFLAGS=… CONTRACT_INC=… sabotage.sh <scratch-dir> <libomxdsp-contracts.a>
set -euo pipefail
HERE="$(cd "$(dirname "$0")" && pwd)"
PKG="$(cd "$HERE/../.." && pwd)"
OUT="${1:?scratch dir}"
LIBC="${2:?contracts archive}"
CC="${CC:-cc}"
CFLAGS="${CFLAGS:--Wall -Wextra -Werror -O2}"
: "${CONTRACT_INC:=$(sh "$PKG/tools/contract-include.sh")}"   # make exports it
mkdir -p "$OUT/gen"

# the mix arms alone, in the suite's harness
{
  echo "/* GENERATED by test/mix/sabotage.sh: the mix arms of test/kernels/ alone. */"
  names=()
  for f in "$PKG"/test/kernels/mix_*.c; do
    echo "#include \"$f\""
    names+=("arm_$(basename "$f" .c)")
  done
  echo "static void (*const OMXDSP_ARMS[])(void) = {"
  for n in "${names[@]}"; do echo "  $n,"; done
  echo "};"
  echo "#define OMXDSP_ARM_COUNT ((int)(sizeof(OMXDSP_ARMS) / sizeof(OMXDSP_ARMS[0])))"
} > "$OUT/gen/kernels-suite.inc.c"

build() { # $1 = dir (its omxdsp/ copy goes ahead of include/)
  # the mix arms alone leave the harness's helpers for other arms unused
  $CC $CFLAGS -Wno-unused-function -ffp-contract=off -I"$1" -I"$PKG/include" -isystem "$CONTRACT_INC" -DOMX_CONTRACTS -I"$OUT/gen" \
    -o "$1/suite" "$PKG/test/omxdsp_suite.c" "$LIBC" -lm
  $CC $CFLAGS -ffp-contract=off -I"$1" -I"$PKG/include" -isystem "$CONTRACT_INC" \
    -o "$1/golden" "$PKG/test/mix/golden.test.c" -lm
}

# the control: the mix arms pass and the digests hold (the suite's contract floor is the whole
# suite's, so its exit status is not read here)
ctl="$OUT/control"
rm -rf "$ctl" && mkdir -p "$ctl"
build "$ctl"
"$ctl/suite" > "$ctl/suite.log" || true
if grep -qE '^(FAIL \[|VIOLATION)' "$ctl/suite.log"; then
  echo "mix-sabotage: FAIL — the mix arms fail against the real headers:"
  grep -E '^(FAIL \[|VIOLATION)' "$ctl/suite.log" | head -10
  exit 1
fi
"$ctl/golden" "$PKG/test/golden/mix.sha256"
echo "mix-sabotage: control — $(grep -oE '^omxdsp_suite: [0-9]+ checks, 0 failed' "$ctl/suite.log") in the mix arms"

run() { # $1 = kernel (its digest name), $2 = arm, $3 = header under omxdsp/mix/, $4 = sed expression
  local dir="$OUT/$1" h="omxdsp/mix/$3"
  rm -rf "$dir" && mkdir -p "$dir"
  cp -r "$PKG/include/omxdsp" "$dir/"
  sed -i "$4" "$dir/$h"
  if cmp -s "$PKG/include/$h" "$dir/$h"; then
    echo "mix-sabotage: FAIL — the $1 sabotage matched nothing in $h; the line it targets is gone"
    exit 1
  fi
  build "$dir"
  "$dir/suite" > "$dir/suite.log" || true
  if ! grep -qE "^FAIL \[$2\]" "$dir/suite.log"; then
    echo "mix-sabotage: FAIL — the $1 sabotage left the $2 arm green"
    exit 1
  fi
  if "$dir/golden" "$PKG/test/golden/mix.sha256" > "$dir/golden.log" 2>&1 ||
     ! grep -qE "^FAIL: $1 [0-9]+ Hz output moved" "$dir/golden.log"; then
    echo "mix-sabotage: FAIL — the $1 sabotage did not move the $1 digests"
    exit 1
  fi
  echo "mix-sabotage: $1 — $(grep -cE "^FAIL \[$2\]" "$dir/suite.log") $2 checks fail, $(grep -cE "^FAIL: $1 " "$dir/golden.log") $1 digests move"
}

run pan mix_pan_law omx_pan_law.h 's|  g\[k + 1u\] = sinf(theta);|  g[k + 1u] = sinf(theta) * 0.9999f;|'
run lcr mix_pan_law omx_pan_law.h 's|  const float phantom = sqrtf(phantom_sq);|  const float phantom = sqrtf(phantom_sq) * 0.9999f;|'
run strip mix_coef omx_mix_coef.h 's|  return gain \* fader \* (mute ? 0.0f : 1.0f);|  return gain * fader * (mute ? 0.0f : 1.0001f);|'
run fold mix_coef omx_mix_coef.h 's|  float t = level \* fold_coef;|  float t = level * fold_coef * 1.0001f;|'
run bus_out mix_bus_out omx_bus_out.h 's|    busL\[i\] \*= omx_ramp_at(rl, i);|    busL[i] *= omx_ramp_at(rl, i) * 0.9999f;|'
run peak mix_meter omx_meter.h 's|      if (y > peak) peak = y;|      if (y > peak) peak = x;|'
run clip mix_meter omx_meter.h 's|      if (run_b >= need) return true;|      if (run_b > need) return true;|'
run hold mix_meter omx_meter.h 's|  return peak > held ? peak : held;|  return peak > held ? peak : held * 0.9999f;|'
run gr mix_meter_gr omx_meter.h 's|    m->hold_left_s = OMX_METER_GR_HOLD_MS \* 0.001f;|    m->hold_left_s = OMX_METER_GR_HOLD_MS * 0.0011f;|'
run rta mix_rta_tap omx_rta_tap.h 's|  for (uint32_t i = 0; i < n; i++) out\[i\] = 0.5f \* (l\[i\] + r\[i\]);|  for (uint32_t i = 0; i < n; i++) out[i] = 0.5001f * (l[i] + r[i]);|'
run rta mix_rta_tap omx_rta_tap.h 's|  omx_decimate_halfband(scr->stage2, OMX_RTA_LOW_WINDOW / 4, scr->low_block);|  omx_decimate_halfband(scr->stage1, OMX_RTA_LOW_WINDOW / 4, scr->low_block);|'
echo "mix-sabotage: every kernel's sabotage turns its oracle and its digests red"
